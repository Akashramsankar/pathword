// Builds public/js/puzzles.js from puzzles/bank.json.
//
//   node scripts/build-puzzles.mjs
//
// The bank is played in order: entry 0 is Pathword #1 (launch day), entry 1 is #2, and so on.
// To add puzzles, append { "answer": "SIXLTR", "grid": ["ROW1..", ...6 rows of 6 letters] }
// to the end of bank.json and rebuild. Never reorder or edit entries that have already
// been played, or past days in the archive will change under players.
//
// For each puzzle the build:
//   1. finds the hidden path (one letter per row, no column used twice) and rejects
//      the puzzle if there isn't exactly one;
//   2. replaces any extra copy of a row's answer letter, so the only right tile on a
//      shelf is the one on the path;
//   3. shuffles the columns with a seed taken from the puzzle number. The marble tips
//      toward the answer's position, so the many bank grids that share a path shape
//      would otherwise be memorisable. The shuffle is fixed, so every player gets the
//      same board.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const bank = JSON.parse(fs.readFileSync(path.join(root, 'puzzles/bank.json'), 'utf8'));


function rng(seed) {
  let s = seed >>> 0;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function paths(grid, answer) {
  const found = [];
  const walk = (r, used, cols) => {
    if (r === 6) { found.push(cols.slice()); return; }
    for (let c = 0; c < 6; c++) {
      if (used.has(c) || grid[r][c] !== answer[r]) continue;
      used.add(c); cols.push(c);
      walk(r + 1, used, cols);
      cols.pop(); used.delete(c);
    }
  };
  walk(0, new Set(), []);
  return found;
}

const ALPHA = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const errors = [];
const answers = new Set();
const out = bank.map((p, i) => {
  const answer = String(p.answer || '').toUpperCase();
  const grid = (p.grid || []).map((row) => String(row).toUpperCase().split(''));
  const where = `#${i + 1} ${answer}`;
  if (!/^[A-Z]{6}$/.test(answer)) errors.push(`${where}: answer must be 6 letters`);
  if (grid.length !== 6 || grid.some((r) => r.length !== 6 || r.some((ch) => !ALPHA.includes(ch)))) {
    errors.push(`${where}: grid must be 6 rows of 6 letters`);
    return null;
  }
  if (answers.has(answer)) errors.push(`${where}: answer already used earlier in the bank`);
  answers.add(answer);
  const found = paths(grid, answer);
  if (found.length !== 1) { errors.push(`${where}: expected exactly 1 hidden path, found ${found.length}`); return null; }
  const cols = found[0];

  const R = rng(0x9e3779b1 ^ (i * 2654435761));
  // 2. one right tile per shelf
  for (let r = 0; r < 6; r++) {
    for (let c = 0; c < 6; c++) {
      if (c === cols[r] || grid[r][c] !== answer[r]) continue;
      const pool = ALPHA.split('').filter((ch) => !grid[r].includes(ch));
      grid[r][c] = pool[Math.floor(R() * pool.length)];
    }
  }
  // 3. fixed column shuffle
  const perm = [0, 1, 2, 3, 4, 5];
  for (let k = 5; k > 0; k--) {
    const j = Math.floor(R() * (k + 1));
    [perm[k], perm[j]] = [perm[j], perm[k]];
  }
  const shuffled = grid.map((row) => perm.map((c) => row[c]).join(''));
  const check = paths(shuffled.map((r) => r.split('')), answer);
  if (check.length !== 1) errors.push(`${where}: shuffle broke the path`);
  return `${answer}${shuffled.join('')}${check[0].join('')}`;
});

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const body = `/* Generated by scripts/build-puzzles.mjs from puzzles/bank.json. Do not edit by hand.
   One entry per day from launch: 6-letter answer + 36 grid letters (row by row) + the
   path's column for each row. */
self.PATHWORD_PUZZLES = ${JSON.stringify(out).replace(/","/g, '",\n"')};
`;
fs.writeFileSync(path.join(root, 'public/js/puzzles.js'), body);
console.log(`Wrote ${out.length} puzzles to public/js/puzzles.js`);
